use crate::context::DeviceContext;
use ash::vk;
use govno_core::BoxError;
use std::{io::Cursor, sync::Arc};

#[derive(Clone, Copy, PartialEq, Eq)]
enum Pass {
    Forward,
    Post,
    Shadow,
}
pub(crate) struct ForwardPipeline {
    ctx: Arc<DeviceContext>,
    pub pipeline: vk::Pipeline,
    pub layout: vk::PipelineLayout,
}
struct ShaderModule {
    ctx: Arc<DeviceContext>,
    handle: vk::ShaderModule,
}
impl ShaderModule {
    fn new(
        ctx: Arc<DeviceContext>,
        bytes: &[u8],
        entry: &std::ffi::CStr,
    ) -> Result<Self, BoxError> {
        crate::reflection::graphics(bytes, entry)?;
        let code = ash::util::read_spv(&mut Cursor::new(bytes))?;
        // SAFETY: embedded SPIR-V is generated by Slang and validated with spirv-val;
        // read_spv supplies aligned words, and the module immediately has an owner.
        let handle = unsafe {
            ctx.device
                .create_shader_module(&vk::ShaderModuleCreateInfo::default().code(&code), None)?
        };
        Ok(Self { ctx, handle })
    }
}
impl Drop for ShaderModule {
    fn drop(&mut self) {
        // SAFETY: pipeline creation has finished; modules need not outlive pipelines.
        unsafe {
            self.ctx.device.destroy_shader_module(self.handle, None);
        }
    }
}
impl ForwardPipeline {
    pub fn new(
        ctx: Arc<DeviceContext>,
        format: vk::Format,
        depth_format: vk::Format,
        scene_layout: vk::DescriptorSetLayout,
    ) -> Result<Self, BoxError> {
        Self::build(ctx, format, depth_format, scene_layout, Pass::Forward)
    }
    pub fn post(
        ctx: Arc<DeviceContext>,
        format: vk::Format,
        layout: vk::DescriptorSetLayout,
    ) -> Result<Self, BoxError> {
        Self::build(ctx, format, vk::Format::UNDEFINED, layout, Pass::Post)
    }
    pub fn shadow(ctx: Arc<DeviceContext>) -> Result<Self, BoxError> {
        Self::build(
            ctx,
            vk::Format::UNDEFINED,
            vk::Format::D32_SFLOAT,
            vk::DescriptorSetLayout::null(),
            Pass::Shadow,
        )
    }
    fn build(
        ctx: Arc<DeviceContext>,
        format: vk::Format,
        depth_format: vk::Format,
        scene_layout: vk::DescriptorSetLayout,
        pass: Pass,
    ) -> Result<Self, BoxError> {
        let pipeline_started = std::time::Instant::now();
        let post = pass == Pass::Post;
        let shadow = pass == Pass::Shadow;
        let vertex = ShaderModule::new(
            ctx.clone(),
            if post {
                include_bytes!("../shaders/postVertex.spv")
            } else if shadow {
                include_bytes!("../shaders/shadowVertex.spv")
            } else {
                include_bytes!("../shaders/vertexMain.spv")
            },
            if post {
                c"postVertex"
            } else if shadow {
                c"shadowVertex"
            } else {
                c"vertexMain"
            },
        )?;
        let fragment = ShaderModule::new(
            ctx.clone(),
            if post {
                include_bytes!("../shaders/postFragment.spv")
            } else {
                include_bytes!("../shaders/fragmentMain.spv")
            },
            if post {
                c"postFragment"
            } else {
                c"fragmentMain"
            },
        )?;
        let mut owner = Self {
            ctx,
            pipeline: vk::Pipeline::null(),
            layout: vk::PipelineLayout::null(),
        };
        let mut stages = vec![
            vk::PipelineShaderStageCreateInfo::default()
                .stage(vk::ShaderStageFlags::VERTEX)
                .module(vertex.handle)
                .name(if post {
                    c"postVertex"
                } else if shadow {
                    c"shadowVertex"
                } else {
                    c"vertexMain"
                }),
            vk::PipelineShaderStageCreateInfo::default()
                .stage(vk::ShaderStageFlags::FRAGMENT)
                .module(fragment.handle)
                .name(if post {
                    c"postFragment"
                } else {
                    c"fragmentMain"
                }),
        ];
        if shadow {
            stages.truncate(1);
        }
        let bindings = [vk::VertexInputBindingDescription {
            binding: 0,
            stride: 48,
            input_rate: vk::VertexInputRate::VERTEX,
        }];
        let attributes = [
            vk::VertexInputAttributeDescription {
                location: 3,
                binding: 0,
                format: vk::Format::R32G32B32A32_SFLOAT,
                offset: 32,
            },
            vk::VertexInputAttributeDescription {
                location: 2,
                binding: 0,
                format: vk::Format::R32G32_SFLOAT,
                offset: 24,
            },
            vk::VertexInputAttributeDescription {
                location: 0,
                binding: 0,
                format: vk::Format::R32G32B32_SFLOAT,
                offset: 0,
            },
            vk::VertexInputAttributeDescription {
                location: 1,
                binding: 0,
                format: vk::Format::R32G32B32_SFLOAT,
                offset: 12,
            },
        ];
        let mut vertex_input = vk::PipelineVertexInputStateCreateInfo::default()
            .vertex_binding_descriptions(&bindings)
            .vertex_attribute_descriptions(&attributes);
        if post {
            vertex_input = vk::PipelineVertexInputStateCreateInfo::default();
        }
        if shadow {
            vertex_input = vertex_input.vertex_attribute_descriptions(&attributes[2..3]);
        }
        let depth = vk::PipelineDepthStencilStateCreateInfo::default()
            .depth_test_enable(!post)
            .depth_write_enable(!post)
            .depth_compare_op(if shadow {
                vk::CompareOp::LESS
            } else {
                vk::CompareOp::GREATER
            });
        let assembly = vk::PipelineInputAssemblyStateCreateInfo::default()
            .topology(vk::PrimitiveTopology::TRIANGLE_LIST);
        let viewport = vk::PipelineViewportStateCreateInfo::default()
            .viewport_count(1)
            .scissor_count(1);
        let raster = vk::PipelineRasterizationStateCreateInfo::default()
            .polygon_mode(vk::PolygonMode::FILL)
            .cull_mode(vk::CullModeFlags::NONE)
            .front_face(vk::FrontFace::COUNTER_CLOCKWISE)
            .line_width(1.0)
            .depth_bias_enable(shadow)
            .depth_bias_constant_factor(1.25)
            .depth_bias_slope_factor(1.75);
        let multisample = vk::PipelineMultisampleStateCreateInfo::default()
            .rasterization_samples(vk::SampleCountFlags::TYPE_1);
        let attachments = [vk::PipelineColorBlendAttachmentState::default()
            .color_write_mask(vk::ColorComponentFlags::RGBA)];
        let blend = vk::PipelineColorBlendStateCreateInfo::default().attachments(if shadow {
            &[]
        } else {
            &attachments
        });
        let states = [vk::DynamicState::VIEWPORT, vk::DynamicState::SCISSOR];
        let dynamic = vk::PipelineDynamicStateCreateInfo::default().dynamic_states(&states);
        let formats = [format];
        let mut rendering = vk::PipelineRenderingCreateInfo::default()
            .color_attachment_formats(if shadow { &[] } else { &formats })
            .depth_attachment_format(depth_format);
        let layouts = if shadow {
            vec![]
        } else if post {
            vec![scene_layout]
        } else {
            vec![scene_layout; 4]
        };
        // SAFETY: all borrowed create-info arrays/modules are live for this call.
        // Descriptor layout and push constant ranges match the compiled shader interfaces.
        unsafe {
            owner.layout = owner.ctx.device.create_pipeline_layout(
                &vk::PipelineLayoutCreateInfo::default()
                    .set_layouts(&layouts)
                    .push_constant_ranges(&[vk::PushConstantRange::default()
                        .stage_flags(vk::ShaderStageFlags::VERTEX | vk::ShaderStageFlags::FRAGMENT)
                        .offset(0)
                        .size(if post {
                            crate::post::OUTPUT_BYTES
                        } else if shadow {
                            64
                        } else {
                            crate::scene_gpu::DRAW_BYTES
                        })]),
                None,
            )?;
            let info = vk::GraphicsPipelineCreateInfo::default()
                .stages(&stages)
                .vertex_input_state(&vertex_input)
                .input_assembly_state(&assembly)
                .viewport_state(&viewport)
                .rasterization_state(&raster)
                .multisample_state(&multisample)
                .depth_stencil_state(&depth)
                .color_blend_state(&blend)
                .dynamic_state(&dynamic)
                .layout(owner.layout)
                .push_next(&mut rendering);
            match owner.ctx.device.create_graphics_pipelines(
                owner.ctx.pipeline_cache,
                &[info],
                None,
            ) {
                Ok(pipelines) => owner.pipeline = pipelines[0],
                Err((partial, error)) => {
                    for pipeline in partial {
                        owner.ctx.device.destroy_pipeline(pipeline, None);
                    }
                    return Err(error.into());
                }
            }
        }
        owner.ctx.pipeline_build_ns.fetch_add(
            pipeline_started.elapsed().as_nanos() as u64,
            std::sync::atomic::Ordering::Relaxed,
        );
        owner
            .ctx
            .pipeline_builds
            .fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        Ok(owner)
    }
}
impl Drop for ForwardPipeline {
    fn drop(&mut self) {
        // SAFETY: owning swapchain quiesces GPU submissions before this is dropped;
        // on construction failure no work references these handles.
        unsafe {
            self.ctx.device.destroy_pipeline(self.pipeline, None);
            self.ctx.device.destroy_pipeline_layout(self.layout, None);
        }
    }
}
